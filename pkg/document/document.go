var (
	// ErrDocumentSizeExceedsLimit is returned when the document size exceeds the limit.
	ErrDocumentSizeExceedsLimit = errors.ResourceExhausted("document size exceeds the limit")

	// ErrSchemaValidationFailed is returned when the document schema validation failed.
	ErrSchemaValidationFailed = errors.InvalidArgument("schema validation failed").WithCode("ErrSchemaValidationFailed")

	// ErrRefusedDuringUpdate occurs when Undo or Redo is called from inside an
	// updater. The updater already holds the document lock, so proceeding would
	// deadlock rather than fail.
	ErrRefusedDuringUpdate = errors.FailedPrecond("undo/redo is not allowed during an update")
)

// DocEvent represents the event that occurred in the document.
type DocEvent struct {
	Type      DocEventType
	Presences map[string]presence.Data
}

// DocEventType represents the type of the event that occurred in the document.
type DocEventType string

const (
	// WatchedEvent means that the client has established a connection with the server,
	// enabling real-time synchronization.
	WatchedEvent DocEventType = "watched"

	// UnwatchedEvent means that the client has disconnected from the server,
	// disabling real-time synchronization.
	UnwatchedEvent DocEventType = "unwatched"

	// PresenceChangedEvent means that the presences of the clients who are editing
	// the document have changed.
	PresenceChangedEvent DocEventType = "presence-changed"
)

// Root represents the root of a document.
type Root = json.Object

// Presence represents the presence of a client editing the document.
type Presence = presence.Presence

// PresenceData represents the data of a client's presence.
type PresenceData = presence.Data

// Option configures Options.
type Option func(*Options)

// Options configures how we set up the document.
type Options struct {
	// DisableGC disables garbage collection.
	// NOTE(hackerwins): This is temporary option. We need to remove this option
	// after introducing the garbage collection based on the version vector.
	DisableGC bool

	// DisablePresence gates the document against producing presence
	// changes. When true, Update silently drops any presence emit issued
	// inside the user callback. The Client sets this from the
	// server-fixated value returned in the AttachDocument response so a
	// late attacher cannot pollute a presenceless document even if it
	// did not pass WithDisablePresence locally.
	DisablePresence bool
}

// WithDisableGC configures the document to disable garbage collection.
func WithDisableGC() Option {
	return func(o *Options) {
		o.DisableGC = true
	}
}

// WithDisablePresence configures the document to drop presence changes
// locally. See Options.DisablePresence.
func WithDisablePresence() Option {
	return func(o *Options) {
		o.DisablePresence = true
	}
}

// Document represents a document accessible to the user.
//
// How document works:
// The operations are generated by the proxy while executing user's command on
// the clone. Then the operations will apply the changes into the base json
// root. This is to protect the base json from errors that may occur while user
// edit the document.
type Document struct {
	// mu protects the document from concurrent access.
	mu sync.RWMutex

	// doc is the original data of the actual document.
	doc *InternalDocument

	// options is the options to configure the document.
	options Options

	// cloneRoot is a copy of `doc.root` to be exposed to the user and is used to
	// protect `doc.root`.
	cloneRoot *crdt.Root

	// clonePresences is a copy of `doc.presences` to be exposed to the user and
	// is used to protect `doc.presences`.
	clonePresences *presence.Map

	// history stores the undo/redo stacks of this document.
	history *History

	// updating reports whether an updater passed to Update is currently
	// running. It is set before d.mu is locked and read before d.mu is
	// locked, so Undo and Redo can refuse a re-entrant call from inside an
	// updater instead of deadlocking on the mutex the updater already holds.
	updating atomic.Bool

	// presenceDroppedOnce ensures the warn-log issued when a presenceless
	// document drops a user-supplied presence change fires at most once
	// per Document instance.
	presenceDroppedOnce sync.Once

	// MaxSizeLimit is the maximum size of a document in bytes.
	MaxSizeLimit int

	// SchemaRules is the rules of the schema of the document.
	SchemaRules []types.Rule

	// events is the channel to send events that occurred in the document.
	events chan DocEvent
}

// New creates a new instance of Document.
func New(key key.Key, opts ...Option) *Document {
	var options Options
	for _, opt := range opts {
		opt(&options)
	}

	return &Document{
		doc:     NewInternalDocument(key),
		options: options,
		history: NewHistory(),
		events:  make(chan DocEvent, 1),
	}
}

// Update executes the given updater to update this document.
func (d *Document) Update(
	updater func(root *json.Object, p *Presence) error,
	msgAndArgs ...interface{},
) error {
	// NOTE(hackerwins): This must be set before d.mu.Lock() so that a
	// re-entrant Undo/Redo call from inside the updater observes it before
	// blocking on the mutex this goroutine already holds; otherwise it would
	// deadlock instead of returning ErrRefusedDuringUpdate.
	d.updating.Store(true)
	defer d.updating.Store(false)

	d.mu.Lock()
	defer d.mu.Unlock()

	if d.doc.status == StatusRemoved {
		return ErrDocumentRemoved
	}

	if err := d.ensureClone(); err != nil {
		return err
	}

	actorID := d.ActorID().String()
	presenceData := d.clonePresences.LoadOrStore(actorID, presence.NewData())
	ctx := change.NewContext(
		d.doc.changeID,
		messageFromMsgAndArgs(msgAndArgs...),
		d.cloneRoot,
		presenceData,
	)

	if err := updater(
		json.NewObject(ctx, d.cloneRoot.Object()),
		presence.New(ctx, presenceData),
	); err != nil {
		// NOTE(hackerwins): If the updater fails, we need to remove the cloneRoot and
		// clonePresences to prevent the user from accessing the invalid state.
		d.cloneRoot = nil
		d.clonePresences = nil
		return err
	}

	// Gate any presence emit when the document opted out. We warn once per
	// document so the silent drop is discoverable without log spam if a
	// caller wires presence into a presenceless document by mistake.
	if d.options.DisablePresence && ctx.HasPresenceChange() {
		ctx.DropPresenceChange()
		ctx.ClearReversePresence()
		d.warnPresenceDroppedOnce()
		if !ctx.HasOperations() {
			return nil
		}
	}

	if !ctx.IsPresenceOnlyChange() && len(d.SchemaRules) > 0 {
		result := schema.ValidateYorkieRuleset(d.cloneRoot.Object(), d.SchemaRules)
		if !result.Valid {
			var errorMessages []string
			for _, err := range result.Errors {
				errorMessages = append(errorMessages, err.Message)
			}
			d.cloneRoot = nil
			d.clonePresences = nil
			return fmt.Errorf("%w: %s", ErrSchemaValidationFailed, strings.Join(errorMessages, ", "))
		}
	}

	cloneSize := d.cloneRoot.DocSize()
	if !ctx.IsPresenceOnlyChange() && d.MaxSizeLimit > 0 && d.MaxSizeLimit < cloneSize.Total() {
		// NOTE(hackerwins): If the updater fails, we need to remove the cloneRoot and
		// clonePresences to prevent the user from accessing the invalid state.
		d.cloneRoot = nil
		d.clonePresences = nil
		return ErrDocumentSizeExceedsLimit
	}

	if ctx.HasChange() {
		c := ctx.ToChange()
		executed, reverseOps, err := c.Execute(d.doc.root, d.doc.presences, operations.OpSourceLocal)
		if err != nil {
			return err
		}

		// NOTE(hackerwins): An ArraySet replaces the element at this
		// position with a freshly ticketed value. Any other stacked reverse
		// operation that still references the replaced element's old
		// createdAt must be rewritten to the new one, or it will target a
		// tombstone the next time it runs (document.ts:744-752).
		for _, op := range executed {
			if set, ok := op.(*operations.ArraySet); ok {
				d.history.ReconcileCreatedAt(set.CreatedAt(), set.Value().CreatedAt())
			}
		}

		var reverse []HistoryOperation
		for _, op := range reverseOps {
			reverse = append(reverse, HistoryOperation{Op: op})
		}
		if reversePresence := ctx.ReversePresence(); reversePresence != nil {
			reverse = append(reverse, HistoryOperation{Presence: reversePresence})
		}
		if len(reverse) > 0 {
			d.history.PushUndo(reverse)
		}

		// NOTE(hackerwins): A new local operation invalidates the redo stack.
		if len(executed) > 0 {
			d.history.ClearRedo()
		}

		d.doc.localChanges = append(d.doc.localChanges, c)
		d.doc.changeID = ctx.NextID()
	}

	return nil
}

// CanUndo reports whether there is a change to undo.
func (d *Document) CanUndo() bool {
	if d.updating.Load() {
		return false
	}

	d.mu.Lock()
	defer d.mu.Unlock()
	return d.history.HasUndo()
}

// CanRedo reports whether there is a change to redo.
func (d *Document) CanRedo() bool {
	if d.updating.Load() {
		return false
	}

	d.mu.Lock()
	defer d.mu.Unlock()
	return d.history.HasRedo()
}

// Undo reverses the last local change. It is a no-op when the undo stack is
// empty.
func (d *Document) Undo() error {
	return d.executeUndoRedo(true)
}

// Redo replays the last undone change. It is a no-op when the redo stack is
// empty.
func (d *Document) Redo() error {
	return d.executeUndoRedo(false)
}

// ClearHistory flushes both stacks. Changes made before this call are no
// longer reachable via undo.
func (d *Document) ClearHistory() {
	d.mu.Lock()
	defer d.mu.Unlock()
	d.history.ClearUndo()
	d.history.ClearRedo()
}

// executeUndoRedo pops an entry off the undo or redo stack and replays it
// against the document, pushing the resulting reverse operations onto the
// opposite stack. It is the port of the JS SDK's executeUndoRedo
// (document.ts:2049-2165).
func (d *Document) executeUndoRedo(isUndo bool) error {
	if d.updating.Load() {
		return ErrRefusedDuringUpdate
	}

	d.mu.Lock()
	defer d.mu.Unlock()

	var entries []HistoryOperation
	if isUndo {
		entries = d.history.PopUndo()
	} else {
		entries = d.history.PopRedo()
	}
	if len(entries) == 0 {
		return nil
	}

	if err := d.ensureClone(); err != nil {
		return err
	}

	actorID := d.ActorID().String()
	ctx := change.NewContext(d.doc.changeID, "", d.cloneRoot, d.clonePresences.Load(actorID))
	for _, entry := range entries {
		if entry.Op == nil {
			// Presence entries carry the values undoing (or redoing) the
			// original change should restore. Apply them WithHistory so the
			// resulting entry is itself undoable -- otherwise undoing a
			// presence change would leave nothing on the redo stack.
			data := d.clonePresences.Load(actorID)
			if data == nil {
				data = presence.NewData()
			}
			p := presence.New(ctx, data.DeepCopy())
			for key, value := range entry.Presence {
				p.Set(key, value, presence.WithHistory())
			}
			continue
		}

		ticket := ctx.IssueTimeTicket()
		entry.Op.SetExecutedAt(ticket)

		// NOTE(hackerwins): Both an Add reverse (acting as UndoRemove,
		// restoring a removed array element) and an ArraySet reverse
		// (restoring a value it replaced) give the restored value a fresh
		// createdAt here rather than keeping its original one, or the
		// restored (live) element and its own tombstone would collide under
		// the same identity in the array's internal index -- letting a
		// later GC pass purge the live element by mistake. Any other
		// stacked operation that still references the old createdAt (as its
		// own createdAt, or as a prevCreatedAt) is updated to the new one so
		// it doesn't end up targeting a stale identity. TreeEdit needs the
		// same treatment once its reverse operation exists (document.ts:
		// 2088-2110).
		if addOp, ok := entry.Op.(*operations.Add); ok {
			prev := addOp.Value().CreatedAt()
			addOp.Value().SetCreatedAt(ticket)
			d.history.ReconcileCreatedAt(prev, ticket)
		} else if setOp, ok := entry.Op.(*operations.ArraySet); ok {
			prev := setOp.CreatedAt()
			setOp.Value().SetCreatedAt(ticket)
			d.history.ReconcileCreatedAt(prev, ticket)
		}

		ctx.Push(entry.Op)
	}

	c := ctx.ToChange()
	if _, _, err := c.Execute(d.cloneRoot, d.clonePresences, operations.OpSourceUndoRedo); err != nil {
		return err
	}
	executed, reverseOps, err := c.Execute(d.doc.root, d.doc.presences, operations.OpSourceUndoRedo)
	if err != nil {
		return err
	}

	var reverse []HistoryOperation
	for _, op := range reverseOps {
		reverse = append(reverse, HistoryOperation{Op: op})
	}
	if reversePresence := ctx.ReversePresence(); reversePresence != nil {
		reverse = append(reverse, HistoryOperation{Presence: reversePresence})
	}
	if len(reverse) > 0 {
		if isUndo {
			d.history.PushRedo(reverse)
		} else {
			d.history.PushUndo(reverse)
		}
	}

	if len(executed) == 0 && c.PresenceChange() == nil {
		return nil
	}

	d.doc.localChanges = append(d.doc.localChanges, c)
	d.doc.changeID = ctx.NextID()
	return nil
}

// UndoStackLenForTest returns the undo stack depth for testing.
func (d *Document) UndoStackLenForTest() int {
	return len(d.history.undoStack)
}

// UndoStackTopForTest returns the operations of the most recent entry of the
// undo stack without popping it, for test inspection of reconciliation.
func (d *Document) UndoStackTopForTest() []HistoryOperation {
	if len(d.history.undoStack) == 0 {
		return nil
	}
	return d.history.undoStack[len(d.history.undoStack)-1]
}

// ApplyChangePack applies the given change pack into this document.
func (d *Document) ApplyChangePack(pack *change.Pack) error {
	d.mu.Lock()
	defer d.mu.Unlock()

	// 01. Apply remote changes to both the cloneRoot and the document.
	hasSnapshot := len(pack.Snapshot) > 0

	if hasSnapshot {
		d.cloneRoot = nil
		d.clonePresences = nil
		if err := d.doc.applySnapshot(pack.Snapshot, pack.VersionVector); err != nil {
			return err
		}
	} else {
		if err := d.applyChanges(pack.Changes); err != nil {
			return err
		}
	}

	// 02. Remove local changes applied to server.
	for d.doc.HasLocalChanges() {
		c := d.doc.localChanges[0]
		if c.ClientSeq() > pack.Checkpoint.ClientSeq {
			break
		}
		d.doc.localChanges = d.doc.localChanges[1:]
	}

	if len(pack.Snapshot) > 0 {
		if err := d.applyChanges(d.doc.localChanges); err != nil {
			return err
		}
	}

	// 03. Update the checkpoint.
	d.doc.checkpoint = d.doc.checkpoint.Forward(pack.Checkpoint)

	// 04. Do Garbage collection.
	if !d.options.DisableGC && !hasSnapshot {
		d.GarbageCollect(pack.VersionVector)
	}

	// 05. Update the status.
	if pack.IsRemoved {
		d.SetStatus(StatusRemoved)
	}

	return nil
}

func (d *Document) applyChanges(changes []*change.Change) error {
	if err := d.ensureClone(); err != nil {
		return err
	}

	for _, c := range changes {
		if _, _, err := c.Execute(d.cloneRoot, d.clonePresences, operations.OpSourceRemote); err != nil {
			return err
		}
	}

	events, executed, err := d.doc.ApplyChanges(changes...)
	if err != nil {
		return err
	}

	// A remote change may have moved the text a pending undo/redo Edit
	// refers to; reconcile every stacked Edit against each executed Edit,
	// mirroring Document.applyChange in the JS SDK (document.ts:1552-1566).
	for _, op := range executed {
		if edit, ok := op.(*operations.Edit); ok {
			from, to := edit.NormalizePos(d.doc.root)
			d.history.ReconcileTextEdit(edit.ParentCreatedAt(), from, to, edit.ContentLen())
		}
	}

	for _, e := range events {
		d.events <- e
	}
	return nil
}

