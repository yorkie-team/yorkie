#!/usr/bin/env bash
set -euo pipefail

# Claude Code PreToolUse(Edit|Write) hook: refuse to hand-edit generated Go.
#
# CLAUDE.md says "never hand-edit api/yorkie/v1/*.pb.go" and CI carries a
# codegen-freshness check, so the edit is caught — but only after a commit, a
# push and a CI run, and the agent that made it has by then written more code
# on top of a file `make proto` is about to overwrite. Refusing at the edit
# turns a round trip into a sentence.
#
# SCOPE IS THE GO OUTPUT ONLY. `buf generate` also writes
# api/docs/yorkie/v1/*.openapi.yaml, and those are deliberately NOT guarded:
# MAINTAINING.md §1 has a maintainer hand-edit the `version` in each of them
# on every release. A guard there would block the release procedure the repo
# documents.
#
# FAIL OPEN. If node is missing or the payload is unreadable this allows the
# edit. A guard that vanishes is bad; a guard that stops someone without node
# from editing anything is worse, and CI's freshness check is the backstop
# either way.
#
# Protocol: the hook payload arrives as JSON on stdin. exit 0 allows, exit 2
# blocks and feeds stderr back to Claude as context.

payload=$(cat)

command -v node >/dev/null 2>&1 || exit 0

path=$(printf '%s' "$payload" | node -e '
let raw = "";
process.stdin.on("data", (c) => (raw += c));
process.stdin.on("end", () => {
  try {
    const p = JSON.parse(raw)?.tool_input?.file_path;
    process.stdout.write(typeof p === "string" ? p : "");
  } catch {
    process.stdout.write("");
  }
});
' 2>/dev/null) || exit 0

[ -n "$path" ] || exit 0

case "$path" in
  *api/yorkie/v1/*.pb.go | *api/yorkie/v1/v1connect/*.connect.go) ;;
  *) exit 0 ;;
esac

cat >&2 <<EOF
$path is generated by 'buf generate' and must not be hand-edited.

Change the schema instead, then regenerate:

  1. edit the .proto under api/yorkie/v1/
  2. make proto
  3. make verify

CI verifies the generated files are in step with the .proto, so an edit here
is reverted by the next regeneration.
EOF
exit 2
