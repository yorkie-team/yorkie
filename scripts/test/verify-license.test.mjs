// Tests for the licence-header gate.
//
// Same rule as the sibling suite: everything runs against a PLANTED TREE under
// the OS temp directory, created per test and removed after. Nothing touches
// the repository and nothing shells out to git.

import {
  chmodSync,
  copyFileSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import {
  collectFindings,
  goFiles,
  hasLicenseHeader,
  HEADER_SCAN_LINES,
  LICENSE_CLAUSE,
} from '../verify-license.mjs';

const SCRIPT = fileURLToPath(new URL('../verify-license.mjs', import.meta.url));

/** The header as hand-written files in this repository carry it. */
const BLOCK_HEADER = `/*
 * Copyright 2020 The Yorkie Authors. All rights reserved.
 *
 * ${LICENSE_CLAUSE} (the "License");
 * you may not use this file except in compliance with the License.
 */

package thing
`;

/** The header as the .mjs scripts and some Go files carry it. */
const LINE_HEADER = `// Copyright 2026 The Yorkie Authors
//
// ${LICENSE_CLAUSE} (the "License");
// you may not use this file except in compliance with the License.

package thing
`;

function withTree(files, body) {
  const root = mkdtempSync(path.join(tmpdir(), 'verify-license-'));
  try {
    for (const [rel, contents] of Object.entries(files)) {
      const abs = path.join(root, rel);
      mkdirSync(path.dirname(abs), { recursive: true });
      writeFileSync(abs, contents);
    }
    return body(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test('both header comment styles satisfy the gate', () => {
  assert.equal(hasLicenseHeader(BLOCK_HEADER), true);
  assert.equal(hasLicenseHeader(LINE_HEADER), true);
});

test('a file with no header is a finding', () => {
  withTree({ 'pkg/thing/thing.go': 'package thing\n' }, (root) =>
    assert.deepEqual(collectFindings(root), [
      'pkg/thing/thing.go has no Apache 2.0 header',
    ]),
  );
});

test('a headered tree has no findings', () => {
  withTree(
    { 'pkg/a/a.go': BLOCK_HEADER, 'cmd/b/b.go': LINE_HEADER },
    (root) => assert.deepEqual(collectFindings(root), []),
  );
});

test('findings name every missing file, sorted, and only .go files', () => {
  withTree(
    {
      'z/z.go': 'package z\n',
      'a/a.go': 'package a\n',
      'a/ok.go': LINE_HEADER,
      'a/notgo.md': 'no header here either',
      'a/notgo.proto': 'syntax = "proto3";',
    },
    (root) =>
      assert.deepEqual(collectFindings(root), [
        'a/a.go has no Apache 2.0 header',
        'z/z.go has no Apache 2.0 header',
      ]),
  );
});

test('the clause is found past a leading tool banner', () => {
  // Generated files open with a banner before their header; the scan window
  // exists for exactly this.
  const banner = '// Code generated by protoc-gen-go. DO NOT EDIT.\n'.repeat(5);
  withTree({ 'api/gen.go': banner + LINE_HEADER }, (root) =>
    assert.deepEqual(collectFindings(root), []),
  );
});

test('the clause is not accepted past the scan window', () => {
  // A mention deep in the body of a file is not a header. Without a bound,
  // any file that merely discusses the licence would pass.
  const filler = '// padding\n'.repeat(HEADER_SCAN_LINES + 5);
  withTree({ 'pkg/late.go': `${filler}// ${LICENSE_CLAUSE}\n` }, (root) =>
    assert.deepEqual(collectFindings(root), [
      'pkg/late.go has no Apache 2.0 header',
    ]),
  );
});

test('vendored and generated-output directories are not walked', () => {
  withTree(
    {
      'vendor/x/x.go': 'package x\n',
      'node_modules/y/y.go': 'package y\n',
      'bin/z.go': 'package z\n',
      'binaries/w.go': 'package w\n',
      'pkg/real.go': LINE_HEADER,
    },
    (root) => {
      assert.deepEqual(goFiles(root).files, ['pkg/real.go']);
      assert.deepEqual(collectFindings(root), []);
    },
  );
});

test('a missing root is a finding, not a silent pass', () => {
  const root = mkdtempSync(path.join(tmpdir(), 'verify-license-'));
  rmSync(root, { recursive: true, force: true });
  assert.deepEqual(goFiles(root).files, []);
  assert.match(collectFindings(root)[0], /scanned nothing/);
});

test('a tree with no Go files is a finding, not a silent pass', () => {
  // The regression this guards: point the script at the wrong root — move it
  // into scripts/ci/ and `..` lands on scripts/ — and it walks a tree with no
  // Go in it, finds nothing missing, and exits 0. A green check with no
  // coverage reads exactly like a green check with full coverage.
  withTree({ 'docs/notes.md': 'no Go here', 'pkg/thing.ts': 'export {};' }, (root) =>
    assert.match(collectFindings(root)[0], /scanned nothing/),
  );
});

/**
 * Run the CLI against a planted tree.
 *
 * The script resolves its root from its OWN location (`../`), not from cwd, so
 * a copy is planted at `<tree>/scripts/verify-license.mjs` and `..` lands on
 * the tree. That is also the property the wrong-root guard above protects, so
 * exercising it here keeps the two honest about each other.
 */
function runCliIn(root, { throughSymlink = false } = {}) {
  const scripts = path.join(root, 'scripts');
  mkdirSync(scripts, { recursive: true });
  copyFileSync(SCRIPT, path.join(scripts, 'verify-license.mjs'));
  // Its sibling import, without which the planted copy will not load.
  copyFileSync(
    fileURLToPath(new URL('../direct-run.mjs', import.meta.url)),
    path.join(scripts, 'direct-run.mjs'),
  );

  let entry = path.join(scripts, 'verify-license.mjs');
  if (throughSymlink) {
    const link = path.join(root, 'link-to-scripts');
    symlinkSync(scripts, link, 'dir');
    entry = path.join(link, 'verify-license.mjs');
  }
  return spawnSync(process.execPath, [entry], { encoding: 'utf8' });
}

test('the CLI runs when invoked through a symlinked path', () => {
  // THE SYMLINK IS EXPLICIT, not inherited from the OS. This guards
  // `isDirectRun` comparing realpaths: as plain strings, `process.argv[1]`
  // (what the caller typed) and `import.meta.url` (resolved by the loader)
  // differ here, the CLI block never runs, and the process exits 0 having
  // checked nothing. It happens to reproduce via macOS's /tmp, which is a
  // link to /private/tmp — but on the Linux runner where this actually runs,
  // /tmp is a real directory and the guard would pass while testing nothing.
  withTree({ 'pkg/a.go': 'package a\n' }, (root) => {
    const r = runCliIn(root, { throughSymlink: true });
    assert.equal(r.status, 1, `the CLI did not run: ${JSON.stringify(r.stdout)}`);
    assert.match(r.stdout, /pkg\/a\.go has no Apache 2\.0 header/);
  });
});

test('the CLI exits 1 and names each file when a header is missing', () => {
  withTree({ 'pkg/a.go': 'package a\n', 'pkg/ok.go': LINE_HEADER }, (root) => {
    const r = runCliIn(root);
    assert.equal(r.status, 1, r.stdout + r.stderr);
    assert.match(r.stdout, /pkg\/a\.go has no Apache 2\.0 header/);
    assert.match(r.stdout, /1 file\(s\) missing the header/);
    assert.doesNotMatch(r.stdout, /pkg\/ok\.go/);
  });
});

test('the CLI exits 1 when it scanned nothing', () => {
  withTree({ 'docs/notes.md': 'no Go here' }, (root) => {
    const r = runCliIn(root);
    assert.equal(r.status, 1, r.stdout + r.stderr);
    assert.match(r.stdout, /scanned nothing/);
  });
});

test('the CLI reports the count it actually checked', () => {
  // Against this repository, not a planted tree: the success line is the only
  // place the scan size is visible, and "every Go file" is true of zero.
  const r = spawnSync(process.execPath, [SCRIPT], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const m = r.stdout.match(/Every Go file \((\d+)\) carries/);
  assert.ok(m, `no count in the success line: ${r.stdout}`);
  assert.ok(Number(m[1]) > 100, `implausibly few files scanned: ${m[1]}`);
});

test('an unlistable directory is a finding, not a gap in a green run', () => {
  // The narrower the gap the more convincing the green: one unreadable
  // directory used to mean its Go files were never examined while every other
  // file passed and the run reported success.
  withTree({ 'pkg/ok.go': LINE_HEADER, 'locked/hidden.go': 'package x\n' }, (root) => {
    const locked = path.join(root, 'locked');
    chmodSync(locked, 0o000);
    try {
      if (goFiles(root).files.includes('locked/hidden.go')) return; // running as root
      const findings = collectFindings(root);
      assert.equal(findings.length, 1, `expected one finding, got ${findings}`);
      assert.match(findings[0], /^locked could not be listed \(/);
    } finally {
      chmodSync(locked, 0o755);
    }
  });
});

test('an unreadable Go file is named as unreadable, not as unheadered', () => {
  // The two are different facts and the fix for each is different. Reporting
  // an I/O error as "has no Apache 2.0 header" sends someone to edit a file
  // they cannot open.
  withTree({ 'pkg/ok.go': LINE_HEADER, 'pkg/locked.go': LINE_HEADER }, (root) => {
    const locked = path.join(root, 'pkg', 'locked.go');
    chmodSync(locked, 0o000);
    try {
      let findings;
      try {
        readFileSync(locked, 'utf8');
        return; // readable anyway (running as root)
      } catch {
        findings = collectFindings(root);
      }
      assert.equal(findings.length, 1, `expected one finding, got ${findings}`);
      assert.match(findings[0], /^pkg\/locked\.go could not be read \(/);
      assert.doesNotMatch(findings[0], /no Apache 2\.0 header/);
    } finally {
      chmodSync(locked, 0o644);
    }
  });
});
