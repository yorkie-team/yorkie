// The two questions an index can fail that a link checker cannot ask.
//
// `verify-doc-links.mjs` walks the documentation graph and fails on a link
// that resolves to nothing. Its header names what it deliberately leaves out:
// "This file is about the index's claims; coverage is about its silences."
// Nothing answered the second half. A design document could land, be linked
// from nowhere, and every check in this repository would stay green.
//
// This file holds TWO SEPARATE CHECKS. They are kept apart in the code and
// here because they catch different failures and carry different weight, and
// because conflating them would let one borrow the other's evidence.
//
// ---------------------------------------------------------------------------
// CHECK 1 — COVERAGE. Gating.
// ---------------------------------------------------------------------------
//
// Every `docs/design/*.md` is linked from `docs/design/README.md`, and every
// top-level entry in `scripts/` is named in `scripts/README.md`.
//
// WHY THESE TWO AREAS AND NOT EVERY FILE. An unrooted "is every .md reachable"
// sweep has to except the hundreds of archived task records, and an exception
// list rots — that is the same argument `verify-doc-links.mjs` makes for
// rooting its walk, applied to the opposite direction. These two areas are the
// ones with a HAND-WRITTEN index and a standing instruction to update it:
// `docs/design/TEMPLATE.md` opens with "Make sure to append the document link
// to docs/design/README.md", and `AGENTS.md`-style folder-README upkeep is
// what `scripts/README.md` is. An instruction nobody checks is the thing worth
// checking.
//
// `docs/tasks/**` is deliberately not an area: its index is GENERATED by
// `scripts/tasks-index.sh`, so a coverage check there would assert that a
// script ran.
//
// THE TWO AREAS USE DIFFERENT EVIDENCE, on purpose.
//
//   `docs/design/README.md` is a navigation surface — a reader clicks through
//   it — so a document counts as indexed only when the README LINKS it. The
//   targets come from `verify-doc-links.mjs`'s own `linkTargets`, which means
//   a filename that appears only inside a fence or inline code does not count,
//   for the same reason it does not count there.
//
//   `scripts/README.md` is a reference table, and every entry in it is written
//   as inline code (`` `setup.sh` ``). Running `linkTargets` over that would
//   delete exactly the form the entries take, and demanding links instead
//   would mean linking eleven scripts for no reader benefit. So a MENTION is
//   the evidence — with a boundary rule, because the loose version is worse
//   than nothing: this README names `$GIT_DIR/agent-hooks/` and
//   `agent-review-panel.yml`, so a plain substring search for `agent` passes
//   on a README that never mentions the `agent/` directory. That was the one
//   real finding on this tree.
//
// WHAT THIS DOES NOT CHECK, twice over:
//
//   Whether an index row points at something that exists. That is
//   `verify-doc-links.mjs`, it already does it, and duplicating it here would
//   mean two gates reporting one broken row.
//
//   Whether the mention is a DESCRIPTION. Deleting `scripts/agent/`'s row from
//   its README keeps this green while another row still says "its reach stops
//   at `agent/`" — found by deleting the row and watching nothing happen. The
//   contract is "mentioned", and it is deliberately not "has a table row":
//   that would pin the README's current shape, and the first reformat would be
//   answered by loosening the gate. The failure actually being closed is a new
//   script landing that the README never learns about — zero mentions — which
//   is what this tree had.
//
// ---------------------------------------------------------------------------
// CHECK 2 — STALENESS. Reported, NOT gating.
// ---------------------------------------------------------------------------
//
// A todo in `docs/tasks/active/` with no unchecked `- [ ]` box is a finished
// task nobody archived.
//
// THIS IS NOT THE COVERAGE CHECK WEARING A HAT, and the distinction is the
// reason both exist. The failure that motivated this file was four task
// records merging to `main` while sitting in `active/` — and coverage cannot
// see it, because nothing was uncovered: the index and the filesystem agreed,
// and both of them said "active". Only the CONTENT of the todo knows the work
// is done.
//
// WHY IT DOES NOT GATE. `CLAUDE.md` step 6 archives a task pair *before merge*,
// after CI is green — so "every box checked, still in `active/`" is the normal
// state of a pull request that has just finished its work, including the one
// that introduces this file. A gate that refuses the last commit of every task
// is a gate that gets bypassed by reflex, and a bypassed gate is worse than a
// printed line because it teaches people the flag. So this reports, exits 0,
// and leaves the decision to the reader of the `Docs` job log — where drift on
// `main` shows up on the very next push.
//
// The predicate is `tasks-archive.sh`'s, character for character: any line
// containing an unchecked box. Agreeing with the script that would do the move
// matters more than being cleverer than it — if the two disagreed, this would
// name files the archiver then refuses to touch. The visible cost is a shared
// blind spot: a todo that QUOTES the box syntax in prose — this file's own
// task record did, before it was reworded — reads as unfinished to both. That
// is the right way round. The alternative is a notice naming a file the
// archiver will not move.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { isDirectRun } from './direct-run.mjs';
import { linkTargets } from './verify-doc-links.mjs';

const PREFIX = '[verify:doc-index]';

/** The design-document index, relative to the repository root. */
export const DESIGN_INDEX = 'docs/design/README.md';

/** The scripts index, relative to the repository root. */
export const SCRIPTS_INDEX = 'scripts/README.md';

/** Where unfinished task pairs live, relative to the repository root. */
export const ACTIVE_TASKS = 'docs/tasks/active';

function isDirectory(target) {
  try {
    return statSync(target).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Every design document under `docs/design/`, sorted, excluding its own index.
 *
 * `TEMPLATE.md` is NOT excluded: the README links it in its opening line, so
 * it needs no exception — and an exception list that starts at one entry is
 * how it gets to five.
 */
export function designDocs(repoRoot) {
  const dir = path.resolve(repoRoot, 'docs', 'design');
  if (!isDirectory(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.md') && e.name !== 'README.md')
    .map((e) => e.name)
    .sort();
}

/**
 * Every top-level entry under `scripts/`, sorted, directories spelled with a
 * trailing slash and the index itself excluded.
 *
 * THE TRAILING SLASH IS LOAD-BEARING, not cosmetic: it is what makes
 * `agent-hooks/` fail to satisfy `agent/`. Dot entries are skipped — they are
 * tool state, not something a reader navigates to.
 */
export function scriptEntries(repoRoot) {
  const dir = path.resolve(repoRoot, 'scripts');
  if (!isDirectory(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => !e.name.startsWith('.') && e.name !== 'README.md')
    .map((e) => (e.isDirectory() ? `${e.name}/` : e.name))
    .sort();
}

/**
 * Does `indexText` name `entry`?
 *
 * The match is anchored on its left by "not a word character and not a
 * hyphen". A `/` is allowed to precede, so `scripts/agent/` counts as naming
 * `agent/` — it is a mention, spelled the long way. A hyphen is not, so
 * `agent-hooks/` does not count as naming `hooks/`, and `.githooks/` does not
 * either.
 *
 * There is no right-hand anchor for directories, so `hooks/install.mjs`
 * counts as naming `hooks/`. That is the honest reading: a README that walks
 * the reader into a directory has introduced it.
 */
export function mentions(indexText, entry) {
  const escaped = entry.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![\\w-])${escaped}`).test(indexText);
}

/**
 * Design documents the index does not link.
 *
 * `checked` separates "this area is clean" from "this area is not here",
 * which the caller needs to tell a passing run from a collapsed one.
 */
function designCoverage(repoRoot) {
  const dir = path.resolve(repoRoot, 'docs', 'design');
  if (!isDirectory(dir)) return { checked: false, findings: [] };

  const indexAbs = path.resolve(repoRoot, DESIGN_INDEX);
  if (!existsSync(indexAbs)) {
    return { checked: true, findings: [`${DESIGN_INDEX} is missing — nothing indexes docs/design/`] };
  }

  const indexed = new Set();
  for (const target of linkTargets(readFileSync(indexAbs, 'utf8'))) {
    const abs = path.resolve(dir, target);
    // Only siblings of the index count. The README also links `media/*.png`
    // and `../../CONTRIBUTING.md`, and neither is a design document.
    if (path.dirname(abs) !== dir) continue;
    indexed.add(path.basename(abs));
  }

  const findings = designDocs(repoRoot)
    .filter((name) => !indexed.has(name))
    .map((name) => `docs/design/${name} is not linked from ${DESIGN_INDEX}`);
  return { checked: true, findings };
}

/** Top-level `scripts/` entries the README never names. */
function scriptsCoverage(repoRoot) {
  const dir = path.resolve(repoRoot, 'scripts');
  if (!isDirectory(dir)) return { checked: false, findings: [] };

  const indexAbs = path.resolve(repoRoot, SCRIPTS_INDEX);
  if (!existsSync(indexAbs)) {
    return { checked: true, findings: [`${SCRIPTS_INDEX} is missing — nothing indexes scripts/`] };
  }

  const text = readFileSync(indexAbs, 'utf8');
  const findings = scriptEntries(repoRoot)
    .filter((entry) => !mentions(text, entry))
    .map((entry) => `scripts/${entry} is not mentioned in ${SCRIPTS_INDEX}`);
  return { checked: true, findings };
}

/**
 * CHECK 1. Every indexed area's uncovered entries, for `repoRoot`.
 *
 * Pure over a directory so the suite can point it at a planted tree — the only
 * way to prove an unindexed file is actually caught.
 *
 * SCANNING NOTHING IS A FINDING, not a pass, exactly as in
 * `verify-license.mjs`: a wrong root walks a tree with no indexed area in it,
 * reports zero gaps and exits 0. An area that is simply absent from the tree
 * is not an error — a planted tree holds one area or the other — but an
 * absence of ALL of them means this check covered nothing.
 */
export function collectFindings(repoRoot) {
  const areas = [designCoverage(repoRoot), scriptsCoverage(repoRoot)];
  if (!areas.some((a) => a.checked)) {
    return [`no indexed area found under ${repoRoot} — this check scanned nothing`];
  }
  return areas.flatMap((a) => a.findings);
}

/**
 * The same predicate `scripts/tasks-archive.sh` applies before it moves a
 * todo: any line containing an unchecked box.
 */
export function hasUncheckedBox(todo) {
  return /- \[ \]/.test(todo);
}

/**
 * CHECK 2. Finished todos still sitting in `docs/tasks/active/`.
 *
 * Returned separately from `collectFindings` rather than tagged with a
 * severity, so a caller cannot accidentally gate on it — the separation is the
 * mechanism, not a convention.
 */
export function collectStaleTasks(repoRoot) {
  const dir = path.resolve(repoRoot, ACTIVE_TASKS);
  if (!isDirectory(dir)) return [];

  const notices = [];
  for (const name of readdirSync(dir).filter((n) => n.endsWith('-todo.md')).sort()) {
    const todo = readFileSync(path.join(dir, name), 'utf8');
    if (hasUncheckedBox(todo)) continue;
    // A missing `**Created**` line is worth naming here because it is the
    // OTHER bar `tasks-archive.sh` applies: such a todo is warned about and
    // left behind, so it would drift even after someone ran the archiver.
    const undated = !/^\*\*Created\*\*:/m.test(todo)
      ? ', and carries no **Created** line for tasks-archive.sh to bucket it by'
      : '';
    notices.push(`${ACTIVE_TASKS}/${name} has every box checked${undated}`);
  }
  return notices;
}

if (isDirectRun(import.meta.url)) {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

  // Reported first, and never touches the exit status. See CHECK 2 above.
  const stale = collectStaleTasks(repoRoot);
  for (const notice of stale) console.log(`${PREFIX}   ${notice}`);
  if (stale.length > 0) {
    console.log(
      `${PREFIX} ${stale.length} finished task(s) still in ${ACTIVE_TASKS}/ — ` +
        'run scripts/tasks-archive.sh at merge. Not a failure.',
    );
  }

  const findings = collectFindings(repoRoot);
  if (findings.length === 0) {
    // The counts are in the success line for the reason verify-license.mjs
    // puts one there: "every design document is indexed" is true of a tree
    // with none, and the number is what makes a collapsed scan visible.
    console.log(
      `${PREFIX} Every design document (${designDocs(repoRoot).length}) is indexed by ` +
        `${DESIGN_INDEX}, and every scripts/ entry (${scriptEntries(repoRoot).length}) by ` +
        `${SCRIPTS_INDEX}.`,
    );
  } else {
    for (const finding of findings) console.log(`${PREFIX}   ${finding}`);
    console.log(`${PREFIX} ${findings.length} unindexed entr(y/ies) found.`);
    process.exit(1);
  }
}
